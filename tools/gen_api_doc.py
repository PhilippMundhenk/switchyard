"""Write docs/API.md from the OpenAPI description of the app (keeps the doc complete)."""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from switchyard import config as cfg  # noqa: E402
from switchyard.web.app import create_app  # noqa: E402


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app(cfg.load(tmp, env={"SWITCHYARD_AUTH_PASSWORD": "x"}))
        paths = app.openapi()["paths"]
    lines = [
        "# HTTP API",
        "",
        "Generated by `python tools/gen_api_doc.py`. The machine-readable description is served at",
        "`/api/openapi.json` (needs a session). All routes except login, session and health need a",
        "session cookie; the read-only viewer login is refused (403) on everything that changes state.",
        "`{mac}` is the switch MAC address, for example `00:11:22:33:44:55` (upper case and dashes work).",
        'Errors are JSON: `{"code": ..., "message": ...}`.',
        "",
        "| Method | Route | What |",
        "| --- | --- | --- |",
    ]
    for route, methods in sorted(paths.items()):
        for method, spec in sorted(methods.items()):
            summary = (spec.get("summary") or "").replace("|", "/")
            lines.append(f"| {method.upper()} | `{route}` | {summary} |")
    lines += [
        "",
        "Also: `GET /metrics` (Prometheus text; session or bearer token) and `GET /health`.",
        "",
    ]
    (ROOT / "docs" / "API.md").write_text("\n".join(lines))
    print(f"{sum(len(m) for m in paths.values())} routes documented")


if __name__ == "__main__":
    main()
